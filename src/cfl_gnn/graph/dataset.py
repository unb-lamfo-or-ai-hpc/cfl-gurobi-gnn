"""
Dataset: NeuralDivingDataset
============================
Optimized dataset class for PyG HeteroData graphs, featuring disk I/O
caching to prevent performance bottlenecks on HPC/DGX clusters.

Design Notes:
    - _file_cache MUST be initialized before super().__init__() because
      PyG's Dataset.__init__ internally calls _process(), which accesses
      the processed_file_names property before __init__ completes.
    - weights_only=False is required for HeteroData objects (custom PyG
      objects are not pure tensor dicts and cannot use weights_only=True).
"""

import os
import torch
from torch_geometric.data import Dataset


class NeuralDivingDataset(Dataset):
    """
    Dataset class for loading pre-processed HeteroData bipartite graphs
    generated by the Neural Diving pipeline.

    Implements a lazy file-list cache so that os.listdir() is called only
    once per Dataset instantiation, avoiding millions of redundant disk
    reads during multi-epoch DGX training.

    File naming convention: processed/data_{idx}.pt
        where idx is a zero-based integer index assigned during ETL.

    Args:
        root (str): Base directory. PyG will look for graphs inside
                    root/processed/data_*.pt
        transform: Optional PyG transform applied at load time.
        pre_transform: Optional PyG transform applied at save time.
    """

    def __init__(self, root, transform=None, pre_transform=None):
        # CRITICAL: _file_cache must be set before super().__init__().
        # PyG's Dataset.__init__ calls _process() -> processed_file_names
        # before this __init__ body would otherwise reach this assignment.
        # Setting it here first prevents AttributeError on first access.
        self._file_cache = None
        super().__init__(root, transform, pre_transform)

    @property
    def processed_file_names(self):
        """
        Returns a deterministically sorted, cached list of processed .pt
        file names relative to self.processed_dir.

        The list is computed once on first access and stored in
        self._file_cache to avoid redundant os.listdir() calls during
        DataLoader iteration.

        Returns:
            list[str]: Sorted list of filenames of the form 'data_{idx}.pt'.
        """
        if self._file_cache is None:
            if not os.path.exists(self.processed_dir):
                self._file_cache = []
            else:
                files = [
                    f for f in os.listdir(self.processed_dir)
                    if f.startswith('data_') and f.endswith('.pt')
                ]
                # Sort numerically by the integer index in 'data_{idx}.pt'
                # to guarantee deterministic, reproducible ordering across
                # different OS filesystem layouts.
                files.sort(key=lambda x: int(x.split('_')[1].split('.')[0]))
                self._file_cache = files
        return self._file_cache

    def len(self):
        """
        Returns the total number of graphs in this dataset.

        Returns:
            int: Number of processed .pt files found in processed_dir.
        """
        return len(self.processed_file_names)

    def get(self, idx):
        """
        Loads a single HeteroData graph object from disk.

        Args:
            idx (int): Zero-based index into the sorted file list.

        Returns:
            HeteroData: The loaded graph, including node features,
                        edge indices, edge attributes, target labels,
                        and complexity metadata.
        """
        actual_file = self.processed_file_names[idx]
        file_path = os.path.join(self.processed_dir, actual_file)

        # weights_only=False is required for HeteroData objects.
        # HeteroData stores Python objects (strings, booleans) alongside
        # tensors and therefore cannot be loaded with weights_only=True,
        # which is restricted to pure tensor dictionaries (state dicts).
        data = torch.load(file_path, weights_only=False)
        return data
