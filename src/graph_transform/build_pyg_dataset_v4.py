# Define data structure for features extracted from Gurobi
@dataclass
class ModelFeatures:
    num_vars: int
    num_constrs: int
    num_binary: int
    num_integer: int
    num_continuous: int
    num_nonzeros: int
    var_types: np.ndarray 
    var_obj_coeffs: np.ndarray 
    var_lb: np.ndarray 
    var_ub: np.ndarray 
    var_names: List[str] 
    constr_senses: np.ndarray 
    constr_rhs: np.ndarray 
    constr_names: List[str] 
    constraint_matrix: Dict[str, np.ndarray] 

def build_heterodata_for_instance(instance_dir, original_features, sol_vector, metadata):
    """Assembles a HeteroData graph with robust shape validation and metadata propagation."""
    try:
        graph_data = HeteroData()

        # 1. Variable Features (Columns: Obj, LB, UB, Cont, Bin, Int)
        v_features = torch.cat([
            torch.FloatTensor(original_features.var_obj_coeffs).unsqueeze(-1),
            torch.FloatTensor(original_features.var_lb).unsqueeze(-1),
            torch.FloatTensor(original_features.var_ub).unsqueeze(-1),
            torch.FloatTensor((original_features.var_types == 0).astype(float)).unsqueeze(-1),
            torch.FloatTensor((original_features.var_types == 1).astype(float)).unsqueeze(-1),
            torch.FloatTensor((original_features.var_types == 2).astype(float)).unsqueeze(-1),
        ], dim=1)

        # 2. LP Vector Validation (Shape Check)
        lp_vector = np.zeros(original_features.num_vars) 
        if len(sol_vector) == original_features.num_vars:
            lp_vector = sol_vector
        else:
            print(f"[WARN] Dimension mismatch: Expected {original_features.num_vars}, got {len(sol_vector)}. Padding with zeros.")
        
        v_features = torch.cat([v_features, torch.FloatTensor(lp_vector).unsqueeze(-1)], dim=1)
        graph_data['variable'].x = v_features

        # 3. Propagate Metadata (Complexity Stratification)
        graph_data.complexity_class = metadata.get('complexity_class', 'unknown')
        graph_data.probe_node_count = metadata.get('probe_node_count', -1)
        graph_data.presolve_used    = metadata.get('presolve_used', False)

        return graph_data
    except Exception as e:
        import traceback
        print(f"[Error] Failed on instance {os.path.basename(instance_dir)}: {e}\n{traceback.format_exc()}")
        return None

